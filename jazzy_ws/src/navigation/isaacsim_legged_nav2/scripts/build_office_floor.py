"""Build an extra storey for the office scene: a copy of the ground floor's interior, one storey up.

NVIDIA's office has a ground floor and a basement; its stair cores continue upward but open onto
nothing (the main core is sealed by one tall wall, Cube24). This writes a USD layer that, loaded
over the office scene, adds a first floor with the ground floor's rooms, walls, furniture, floors,
ceilings and lights:

* ``/World/office_floor1`` references ``/World/office`` (shared, instanced assets: cheap) one
  storey up, with everything deactivated except the ground floor's interior: not the stair cores
  (they already have upper-storey geometry), the ground plane, or anything spanning storeys.
* The roof slabs the new floor would sit on (Cube18/19/37) are removed: one is 1 cm above the
  copied floor tiles, one 10 cm below. The copied floor tiles get exact colliders instead.
* Cube24 is replaced by the same wall from the storey above upward, so the first floor opens onto
  the main stairwell while the floors above stay closed.

Run with Isaac Sim's Python; the layer file is written next to the scene:

    ~/isaacsim/python.sh build_office_floor.py [--scene .../dd100_office_navigation.usd] [--out .../office_floor1.usda]
"""

import argparse
import os

STOREY = 3.3  # m between floors (ground floor 0, stair landings and the next floor at 3.3)
CORES = {  # stair cores (x0, x1, y0, y1): their upper storeys already exist in the scene
    "main": (-24.1, -14.85, -9.1, 3.1),
    "small": (-21.1, -17.95, -18.1, -9.05),
}
ROOF_SLABS = ("Cube18", "Cube19", "Cube37")
# ground-floor prims whose upper-storey counterpart already exists: the small core's stairwell door
# (the first floor has its own, BP_PanicDoor6)
NOT_COPIED = ("BP_PanicDoor2_368",)
CORE_WALL = "Cube24"
FLOOR_PREFIX = "SM_Floor"


def main() -> None:
    here = os.path.dirname(os.path.realpath(__file__))
    scenes = os.path.normpath(os.path.join(here, *[".."] * 4, "scenes"))
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--scene", default=os.path.join(scenes, "dd100_office_navigation.usd"))
    parser.add_argument("--out", default=os.path.join(scenes, "office_floor1.usda"))
    args = parser.parse_args()

    from isaacsim import SimulationApp

    app = SimulationApp({"headless": True})
    import omni.usd
    from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade

    stage = omni.usd.get_context().get_stage()
    stage.GetRootLayer().subLayerPaths.append(args.scene)
    for _ in range(10):
        app.update()
    office = stage.GetPrimAtPath("/World/office")
    cache = UsdGeom.BBoxCache(Usd.TimeCode.Default(), ["default", "render"], useExtentsHint=True)

    def bounds(prim):
        r = cache.ComputeWorldBound(prim).ComputeAlignedRange()
        return None if r.IsEmpty() else (r.GetMin(), r.GetMax())

    def inside_core(lo, hi):
        return any(x0 <= lo[0] and hi[0] <= x1 and y0 <= lo[1] and hi[1] <= y1 for x0, x1, y0, y1 in CORES.values())

    keep, skipped = [], {"spans storeys or outside the ground floor": 0, "stair core": 0, "roof slab": 0, "ground plane": 0,
                         "exists upstairs": 0}
    for child in office.GetChildren():
        b = bounds(child)
        name = child.GetName()
        if name in ROOF_SLABS:
            skipped["roof slab"] += 1
        elif name == "GroundPlane":
            skipped["ground plane"] += 1
        elif name in NOT_COPIED:
            skipped["exists upstairs"] += 1
        elif b is None or b[0][2] < -0.35 or b[1][2] > STOREY + 0.06:
            skipped["spans storeys or outside the ground floor"] += 1
        elif inside_core(*b):
            skipped["stair core"] += 1
        else:
            keep.append(child)

    if os.path.exists(args.out):
        os.remove(args.out)
    layer = Sdf.Layer.CreateNew(args.out)
    layer.comment = "Generated by isaacsim_legged_nav2/scripts/build_office_floor.py; do not edit by hand."
    stage.GetRootLayer().subLayerPaths.insert(0, args.out)
    stage.SetEditTarget(Usd.EditTarget(layer))

    # the copy, one storey up
    floor1 = stage.DefinePrim("/World/office_floor1", "Xform")
    floor1.GetReferences().AddInternalReference("/World/office")
    UsdGeom.Xformable(floor1).AddTranslateOp().Set(Gf.Vec3d(0.0, 0.0, STOREY))
    kept = {c.GetName() for c in keep}
    for child in office.GetChildren():
        if child.GetName() not in kept:
            stage.OverridePrim(f"/World/office_floor1/{child.GetName()}").SetActive(False)
    tiles = 0
    for child in keep:
        if not child.GetName().startswith(FLOOR_PREFIX):
            continue
        for mesh in Usd.PrimRange(stage.GetPrimAtPath(f"/World/office_floor1/{child.GetName()}")):
            if mesh.IsA(UsdGeom.Mesh):
                UsdPhysics.CollisionAPI.Apply(mesh)
                UsdPhysics.MeshCollisionAPI.Apply(mesh).CreateApproximationAttr().Set(UsdPhysics.Tokens.none)
                tiles += 1

    # roof slabs under the new floor
    for name in ROOF_SLABS:
        stage.OverridePrim(f"/World/office/{name}").SetActive(False)

    # the stair core's wall: open on the first floor, closed above
    wall = stage.GetPrimAtPath(f"/World/office/{CORE_WALL}")
    lo, hi = bounds(wall)
    material, _ = UsdShade.MaterialBindingAPI(next(p for p in Usd.PrimRange(wall, Usd.TraverseInstanceProxies())
                                                  if p.IsA(UsdGeom.Mesh))).ComputeBoundMaterial()
    stage.OverridePrim(f"/World/office/{CORE_WALL}").SetActive(False)
    upper = UsdGeom.Cube.Define(stage, f"/World/office_floor1_extras/{CORE_WALL}_above_floor1")
    upper.CreateSizeAttr(1.0)
    z0 = 2 * STOREY
    xform = UsdGeom.Xformable(upper)
    xform.AddTranslateOp().Set(Gf.Vec3d((lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, (z0 + hi[2]) / 2))
    xform.AddScaleOp().Set(Gf.Vec3f(max(hi[0] - lo[0], 0.02), hi[1] - lo[1], hi[2] - z0))
    UsdPhysics.CollisionAPI.Apply(upper.GetPrim())
    if material:
        UsdShade.MaterialBindingAPI.Apply(upper.GetPrim()).Bind(material)

    layer.Save()
    print(f"FLOOR1 wrote {args.out}: copied {len(keep)} ground-floor prims one storey up ({tiles} floor meshes with "
          f"colliders); skipped {skipped}; removed roof slabs {ROOF_SLABS}; {CORE_WALL} now starts at z {z0}", flush=True)
    app.close()


if __name__ == "__main__":
    main()
